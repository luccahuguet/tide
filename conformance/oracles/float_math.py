#!/usr/bin/env python3
"""Independent expectations; /usr/bin/python3 conformance/oracles/float_math.py [--write].

Uses system MPFR via ctypes, never Tide/libm or host transcendental functions.
At 256-bit precision, evaluate each operation with directed rounding both ways;
accept its f32/f64 nearest-even result only when both interval ends round alike.
Inputs are first rounded to the tested width. Exact compositions use Fraction.
The output is the marked section of cases/authority/float_math.rs (default: check).

ULP allowances are libm 0.2.16's upstream MPFR test bounds, not a universal proof:
https://github.com/rust-lang/compiler-builtins/blob/dfd2203a4d6110820ad7bb65cafe1bf331a03a3d/libm-test/src/precision.rs#L14-L100
"""
import ctypes as C
from fractions import Fraction as Q
from pathlib import Path
import struct
import sys


class Mpfr(C.Structure):
    _fields_ = [("precision", C.c_long), ("sign", C.c_int),
                ("exponent", C.c_long), ("limbs", C.c_void_p)]


mp = C.CDLL("libmpfr.so.6")
ptr = C.POINTER(Mpfr)
mp.mpfr_init2.argtypes = [ptr, C.c_long]
mp.mpfr_clear.argtypes = [ptr]
mp.mpfr_set_d.argtypes = [ptr, C.c_double, C.c_int]
mp.mpfr_get_d.argtypes = [ptr, C.c_int]
mp.mpfr_get_d.restype = C.c_double
mp.mpfr_get_flt.argtypes = [ptr, C.c_int]
mp.mpfr_get_flt.restype = C.c_float
mp.mpfr_get_version.restype = C.c_char_p


def bits(x, width):
    return int.from_bytes(struct.pack(">f" if width == 32 else ">d", x), "big")


def rounded(x, width):
    return struct.unpack(">f", struct.pack(">f", x))[0] if width == 32 else float(x)


def oracle(name, args, width):
    values = [Mpfr() for _ in range(len(args) + 1)]
    for value in values:
        mp.mpfr_init2(C.byref(value), 256)
    try:
        for value, arg in zip(values, args):
            mp.mpfr_set_d(C.byref(value), rounded(arg, width), 0)
        fn = getattr(mp, "mpfr_" + name)
        fn.argtypes = [ptr] * len(values) + [C.c_int]
        get = mp.mpfr_get_flt if width == 32 else mp.mpfr_get_d
        ends = []
        for mode in [3, 2]:  # MPFR_RNDD and MPFR_RNDU; get uses MPFR_RNDN.
            fn(C.byref(values[-1]), *(C.byref(x) for x in values[:-1]), mode)
            ends.append(bits(get(C.byref(values[-1]), 0), width))
        assert ends[0] == ends[1], (name, args, width, "increase precision")
        return ends[0]
    finally:
        for value in values:
            mp.mpfr_clear(C.byref(value))


def generate():
    lines = ["// BEGIN independent oracle (generated by conformance/oracles/float_math.py)",
             "// MPFR: 256-bit directed intervals certify nearest-even expectations.",
             "// ULP bounds: pinned upstream libm-test/src/precision.rs, linked in the script.",
             "fn independent_numerical_contract() {"]
    unary = "sin cos tan asin acos atan sinh cosh tanh asinh acosh atanh exp exp2 exp_m1 ln ln_1p log2 log10 cbrt".split()
    rename = {"exp_m1": "expm1", "ln": "log", "ln_1p": "log1p", "powf": "pow"}
    bounds = {"acosh": 4, "asinh": 2, "atan2": 2, "atanh": 2,
              "sinh": 2, "tanh": 2, "cbrt": 0}
    cases = [(name, [1.5 if name == "acosh" else 0.5]) for name in unary]
    cases += [("powf", [1.5, 0.75]), ("hypot", [1.25, 0.75]), ("atan2", [1.25, -0.75])]
    for width in [32, 64]:
        current = cases + [("sin", [1e20])]
        if width == 64:
            current += [("exp", [0.019]), ("exp2", [16.077])]
        for name, args in current:
            expected = oracle(rename.get(name, name), args, width)
            call = f"math::{name}(" + ", ".join(f"{x!r}f{width}" for x in args) + ")"
            lines.append(f'    assert!(float::bits({call}).abs_diff(0x{expected:0{width // 4}x}) <= {bounds.get(name, 1)}, "MPFR f{width}::{name}");')
        for index, name in enumerate(["sin", "cos"]):
            expected = oracle(name, [0.5], width)
            lines.append(f'    assert!(float::bits(math::sin_cos(0.5f{width}).{index}).abs_diff(0x{expected:x}) <= 1, "MPFR f{width}::sin_cos.{index}");')
        # These rational formulas are exact before the one final IEEE rounding.
        exact = [("fract(-1.75", Q(-7, 4) - int(Q(-7, 4))),
                 ("recip(0.5", 1 / Q(1, 2)),
                 ("div_euclid(-7.0, 4.0", Q(-7) // Q(4)),
                 ("rem_euclid(-7.0, 4.0", Q(-7) % Q(4)),
                 ("midpoint(1.25, 0.75", (Q(5, 4) + Q(3, 4)) / 2),
                 ("clamp(1.5, 0.0, 1.0", min(max(Q(3, 2), Q(0)), Q(1))),
                 ("powi(2.0, -3", Q(2) ** -3),
                 ("powi(10.0, -2", Q(10) ** -2),
                 ("round_ties_even(2.5", Q(2)),
                 ("abs_sub(1.25, 0.75", max(Q(5, 4) - Q(3, 4), Q(0))),
                 ("log(8.0, 2.0", Q(3))]
        lines.append("    // Exact rational formulas: fract=x-trunc(x), q=floor(x/r), r=x-q*r,")
        lines.append("    // midpoint=(a+b)/2, clamp=min(max(x,lo),hi), powi=x^n, log_2(8)=3.")
        for call, result in exact:
            # Type the first operand so generic dispatch selects the intended width.
            first, sep, rest = call.partition(",")
            call = first + f"f{width}" + (sep + rest if sep else "") + ")"
            expected = bits(rounded(result, width), width)
            lines.append(f'    assert_eq!(float::bits(math::{call}), 0x{expected:x}, "exact f{width}::{call.split("(")[0]}");')
        # Rust core's stated formulas use these rounded binary constants, then multiply.
        lines.append("    // Angle conversions: x * rounded(180/pi), x * rounded(pi/180).")
        for name, x, constant in [("to_degrees", Q(1, 2), "57.2957795130823208767981548141051703"),
                                  ("to_radians", Q(30), "0.017453292519943295769236907684886127")]:
            factor = Q(rounded(float(constant), width))
            expected = bits(rounded(x * factor, width), width)
            lines.append(f'    assert_eq!(float::bits(math::{name}({float(x)}f{width})), 0x{expected:x}, "formula f{width}::{name}");')
    return "\n".join(lines + ["}", "// END independent oracle"])


if __name__ == "__main__":
    # Cheap checks for the ABI and directed-rounding/width conversion glue.
    assert oracle("exp2", [0.5], 32) == 0x3fb504f3
    assert oracle("log2", [0.5], 64) == 0xbff0000000000000
    fixture = Path(__file__).resolve().parents[1] / "cases/authority/float_math.rs"
    text = fixture.read_text()
    begin = "// BEGIN independent oracle"
    end = "// END independent oracle"
    output = generate()
    if begin in text:
        before, section = text.split(begin, 1)
        old, after = section.split(end, 1)
        updated = before + output + after
    else:
        updated = text.replace("#[tide::main]", output + "\n\n#[tide::main]")
    if sys.argv[1:] == ["--write"]:
        fixture.write_text(updated)
    else:
        assert not sys.argv[1:], "only --write is supported"
        assert text == updated, "oracle output differs; run with --write"
    print(f"MPFR {mp.mpfr_get_version().decode()}: certified 256-bit intervals; oracle output matches fixture")

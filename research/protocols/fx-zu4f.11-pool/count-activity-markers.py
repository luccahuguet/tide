#!/usr/bin/env python3
"""Count default-branch commit messages without printing or assessing them."""
import argparse
import csv
import datetime as dt
import hashlib
import json
import pathlib
import re
import subprocess

MARKER_REGEX = (r'(?im:Co-Authored-By:[ \t]*Claude|Generated with \[?Claude Code|'
                r'Co-Authored-By:[^\n]*(Codex|Copilot|Cursor|Aider|Devin|OpenHands|Jules|Amp|Gemini)|'
                r'Generated (with|by) (Codex|Copilot|Cursor|Aider|Devin))|(?i:\Aaider:)')
MARKER = re.compile(MARKER_REGEX)


def counts(repo, commit, start, end):
    # --since-as-filter visits through old-dated commits instead of pruning their descendants.
    command = ['git','-C',str(repo),'log',commit,'--since-as-filter='+start,'--until='+end,
               '--format=%H%x00%ct%x00%B%x00','--no-show-signature']
    result = subprocess.run(command,check=True,capture_output=True,stdin=subprocess.DEVNULL,timeout=300)
    parts = result.stdout.split(b'\x00')
    assert len(parts)%3 == 1 and not parts[-1].strip()
    lo = dt.datetime.fromisoformat(start.replace('Z','+00:00')).timestamp()
    hi = dt.datetime.fromisoformat(end.replace('Z','+00:00')).timestamp()
    total = marked = 0
    for i in range(0,len(parts)-1,3):
        sha,seconds,message = parts[i:i+3]
        assert re.fullmatch(rb'[a-f0-9]{40,64}',sha.strip())
        if lo <= int(seconds) < hi:
            total += 1
            marked += bool(MARKER.search(message.decode('utf-8',errors='replace')))
    return dict(commits=total,marked=marked,share=marked/total if total else 0,
                log_sha256=hashlib.sha256(result.stdout).hexdigest(),command=command)


def self_test():
    import tempfile
    assert MARKER.search('subject\n\nCo-Authored-By: Claude Opus <x>')
    assert MARKER.search('subject\n🤖 Generated with [Claude Code](https://example.test)')
    assert MARKER.search('subject\nCo-Authored-By: Some Codex <x>')
    assert MARKER.search('Generated by Cursor')
    assert MARKER.search('AiDeR: subject')
    assert not MARKER.search('subject\naider: not at start')
    assert not MARKER.search('Co-Authored-By: Human\nGemini is unrelated')
    assert not MARKER.search('Generated by Gemini')
    with tempfile.TemporaryDirectory() as directory:
        repo = pathlib.Path(directory)
        def git(*args, **kwargs):
            return subprocess.check_output(['git','-C',str(repo),*args],**kwargs).decode().strip()
        git('init','--quiet')
        git('config','user.name','Synthetic fixture')
        git('config','user.email','fixture@example.invalid')
        import os
        for date,message in [('2025-01-01T00:00:00Z','old'),('2026-01-01T00:00:00Z','aider: fixture'),('2026-02-01T00:00:00Z','boundary')]:
            git('commit','--quiet','--allow-empty','-m',message,env={**os.environ,'GIT_AUTHOR_DATE':date,'GIT_COMMITTER_DATE':date})
        result = counts(repo,'HEAD','2026-01-01T00:00:00Z','2026-02-01T00:00:00Z')
        assert (result['commits'],result['marked']) == (1,1),result
    print('self-test: passed')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--self-test',action='store_true')
    parser.add_argument('--repo',type=pathlib.Path)
    parser.add_argument('--commit')
    parser.add_argument('--start')
    parser.add_argument('--end')
    args = parser.parse_args()
    if args.self_test:
        self_test()
    else:
        print(json.dumps(counts(args.repo,args.commit,args.start,args.end),sort_keys=True))
